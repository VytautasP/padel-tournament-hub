/**
 * Prints generated schedules to stdout, so fairness can be eyeballed rather than only asserted.
 *
 * Build-order step 1 asks for exactly this: print schedules, read them, and notice what a
 * validator cannot. `formatSchedule` does the rendering — this script only decides which sessions
 * are worth looking at and hands them over. The names below are duplicated from the engine's test
 * fixtures on purpose: this script reads the built package, which does not ship test support.
 *
 *   npm run print:schedule              # the three sessions below
 *   npm run print:schedule -- 12 3 7    # 12 players, 3 courts, 7 rounds
 *
 * It imports the built library, so it also proves the printed output survives the package build
 * rather than only the test bundler. `npm run print:schedule` builds first.
 */
import {
  createSession,
  formatSchedule,
  generateRemaining,
} from '../dist/padel-engine/fesm2022/padel-engine.mjs';

const NAMES = [
  'Ana',
  'Ben',
  'Cara',
  'Dov',
  'Elin',
  'Finn',
  'Gita',
  'Hugo',
  'Iris',
  'Jonas',
  'Kaja',
  'Liam',
  'Mira',
  'Nils',
  'Olga',
  'Pavel',
];

const roster = (count) =>
  Array.from({ length: count }, (_, index) => ({
    id: `p${index + 1}`,
    name: NAMES[index % NAMES.length] ?? `Player ${index + 1}`,
  }));

const exactFit = (id, courtCount, roundCount) =>
  generateRemaining(
    createSession({
      id,
      mode: 'americano',
      players: roster(courtCount * 4),
      courtCount,
      targetScore: 24,
      roundCount,
    }),
  );

/**
 * The roster the build order names by name: 11 players on 2 courts, three of them benched every
 * round. The scheduler is exact-fit for now (ADR-0004), so this one is hand-rotated — it is here
 * to show that a benched schedule stays legible, ahead of the ticket that can generate one.
 */
function awkwardRoster() {
  const players = roster(11);
  const rounds = Array.from({ length: 4 }, (_, index) => {
    const number = index + 1;
    const rotated = [...players.slice((number - 1) * 3), ...players.slice(0, (number - 1) * 3)];
    const playing = rotated.slice(0, 8).map((player) => player.id);

    return {
      id: `awkward:r${number}`,
      number,
      matches: [1, 2].map((courtNumber) => {
        const [a, b, c, d] = playing.slice((courtNumber - 1) * 4, courtNumber * 4);

        return {
          id: `awkward:r${number}:c${courtNumber}`,
          courtNumber,
          sideA: [a, b],
          sideB: [c, d],
        };
      }),
    };
  });

  return {
    id: 'awkward',
    mode: 'americano',
    roster: players,
    courtCount: 2,
    targetScore: 24,
    rounds,
  };
}

/** A usage mistake is the reader's, not the code's — say what is wrong, without a stack trace. */
function usage(message) {
  process.stderr.write(
    `${message}\nUsage: node tools/print-schedule.mjs [players] [courts] [rounds]\n`,
  );
  process.exit(1);
}

function main(argv) {
  if (argv.length > 0) {
    const [players, courts, rounds] = argv.map(Number);
    if (
      argv.length !== 3 ||
      ![players, courts, rounds].every((value) => Number.isInteger(value) && value > 0)
    ) {
      usage('Expected three positive whole numbers.');
    }
    if (players !== courts * 4) {
      usage(
        `Americano on ${courts} court(s) needs exactly ${courts * 4} players — the engine is exact-fit for now (ADR-0004).`,
      );
    }

    return [{ session: exactFit(`cli-${players}p`, courts, rounds) }];
  }

  return [
    // Nine rounds on an eight-player roster: the circle method exhausts every partnership in
    // seven, so rounds 8 and 9 are where repeats show up in the per-player blocks.
    { session: exactFit('session-8p', 2, 9), note: 'Generated by the engine.' },
    { session: exactFit('session-12p', 3, 5), note: 'Generated by the engine.' },
    {
      session: awkwardRoster(),
      note: [
        'NOT generated by the engine — hand-rotated fixture data, because the scheduler is',
        'exact-fit for now (ADR-0004). It is here to show that a benched schedule reads clearly;',
        'its own unevenness is this script rotating naively, not a scheduling bug.',
      ].join('\n'),
    },
  ];
}

for (const { session, note } of main(process.argv.slice(2))) {
  process.stdout.write(`${'='.repeat(72)}\n`);
  if (note) {
    process.stdout.write(`${note}\n${'-'.repeat(72)}\n`);
  }
  process.stdout.write(formatSchedule(session));
  process.stdout.write('\n');
}
